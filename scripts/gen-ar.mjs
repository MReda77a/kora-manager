// Builds lib/ar/dict.ts from the plain lists in lib/ar/src/*.txt (one "English<TAB>Arabic" per line).
// Lines with {0}, {1}... become patterns; the rest are looked up as they are.
import fs from 'node:fs';
const dir = new URL('../lib/ar/src/', import.meta.url);
const exact = {}, patterns = {};
for (const f of fs.readdirSync(dir).filter((f) => f.endsWith('.txt')).sort()) {
  for (const [i, line] of fs.readFileSync(new URL(f, dir), 'utf8').split('\n').entries()) {
    if (!line.trim() || line.startsWith('#')) continue;
    const [en, ar] = line.split('\t');
    if (ar === undefined) throw new Error(`${f}:${i + 1} has no tab: ${line}`);
    let k = en.replace(/\s+/g, ' ').trim(), v = ar.trim();
    // named slots ({score}, {m}) become numbered ones, in the order they appear in the English
    const names = [...new Set([...k.matchAll(/\{([a-z]+)\}/g)].map((m) => m[1]))];
    names.forEach((n, i) => { k = k.split(`{${n}}`).join(`{${i}}`); v = v.split(`{${n}}`).join(`{${i}}`); });
    if (/\{[a-z]+\}/.test(v)) throw new Error(`${f}:${i + 1} Arabic has a slot the English lacks: ${line}`);
    if (!k) continue;
    (/\{\d\}/.test(k) ? patterns : exact)[k] = v;
  }
}
fs.writeFileSync(new URL('../lib/ar/dict.ts', import.meta.url),
  `// generated by scripts/gen-ar.mjs from lib/ar/src: edit those lists, not this file\nimport type { Dict } from '../i18n.ts';\nexport const AR: Dict = ${JSON.stringify({ exact, patterns }, null, 0)};\n`);
console.log('exact', Object.keys(exact).length, 'patterns', Object.keys(patterns).length);
